#!/usr/bin/env python3
"""
Build an AVEVA Custom Widget package (.cwp) that also runs in ScadaCraft.

    python3 make_cwp.py <widget folder>

The folder holds:
  widget.json   name, title, width, height and the property list (single source of truth):
                {"name": "pump_station", "width": 1920, "height": 1080,
                 "properties": [{"name": "pressure", "type": "Integer", "value": "0", "dir": "in",
                                 "desc": "Plant pressure (raw x10)", "tag": "PS_Pressure", "register": "43034"}]}
                type: Boolean | Integer | Double | String;  dir: in (read) | out (command) | inout (read + write)
                tag / register: optional, only for the binding table (not part of the widget)
  index.html    the page; loads ../resources/apis/proxy.js (cwidget="<name>"), build/props.js, build/<name>.js
  build/<name>.js  the page logic (reads cwidget.<prop>, writes cwidget.<prop> = v, cwidget.on('<prop>', fn))
  any other file (css, images) is packed too.

Output, next to the folder:
  <name>.cwp                 the package (AVEVA OMI, ScadaCraft editor import, ScadaCraft MCP import)
  <name>_bindings.csv        property -> tag table (the MCP binds tags from it)
and inside the folder (generated, do not edit): <name>.wjson, build/props.js, sw.js.
"""
import json
import os
import re
import sys
import zipfile

TYPES = {"Boolean", "Integer", "Double", "String"}
DIRS = {"in", "out", "inout"}


def main(folder):
    folder = os.path.abspath(folder)
    spec = json.load(open(os.path.join(folder, "widget.json"), encoding="utf-8"))
    name = spec["name"]
    if not re.fullmatch(r"[A-Za-z][\w-]*", name):
        sys.exit(f"invalid widget name {name!r}: letters, digits, _ and -")
    props = spec["properties"]
    seen = set()
    for p in props:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", p["name"]):
            sys.exit(f"invalid property name {p['name']!r}: lower case letters, digits, _")
        if p["name"] in seen:
            sys.exit(f"duplicate property {p['name']!r}")
        seen.add(p["name"])
        if p.get("type") not in TYPES:
            sys.exit(f"{p['name']}: type must be one of {sorted(TYPES)}")
        p.setdefault("dir", "in")
        if p["dir"] not in DIRS:
            sys.exit(f"{p['name']}: dir must be in, out or inout")
        p.setdefault("value", "false" if p["type"] == "Boolean" else "" if p["type"] == "String" else "0")
        p.setdefault("desc", p["name"])
    for f in ("index.html", f"build/{name}.js"):
        if not os.path.exists(os.path.join(folder, f)):
            sys.exit(f"missing {f}")
    html = open(os.path.join(folder, "index.html"), encoding="utf-8").read()
    if "../resources/apis/proxy.js" not in html:
        sys.exit('index.html must load <script src="../resources/apis/proxy.js" cwidget="%s"></script>' % name)

    wjson = {"version": 0, "useSDK": False, "height": int(spec.get("height", 1080)), "width": int(spec.get("width", 1920)), "events": {},
             "properties": {str(i): {"type": p["type"], "name": p["name"], "value": str(p["value"]), "desc": {"1033": p["desc"]}}
                            for i, p in enumerate(props)}}
    os.makedirs(os.path.join(folder, "build"), exist_ok=True)
    with open(os.path.join(folder, f"{name}.wjson"), "w", encoding="utf-8") as f:
        json.dump(wjson, f, indent=2, ensure_ascii=False)
    with open(os.path.join(folder, "build", "props.js"), "w", encoding="utf-8") as f:
        f.write("// generated by make_cwp.py from widget.json - do not edit\nwindow.CW_PROPS = ")
        json.dump([{k: p[k] for k in ("name", "type", "value", "dir", "desc")} for p in props], f, ensure_ascii=False, indent=1)
        f.write(";\n")

    files = []
    for root, _, names in os.walk(folder):
        for n in names:
            rel = os.path.relpath(os.path.join(root, n), folder).replace(os.sep, "/")
            if rel in ("widget.json", "sw.js") or rel.startswith(".") or "/." in rel:
                continue
            files.append(rel)
    files.sort()
    sw = """const CW_NAME = encodeURI(self.location.pathname.split('/').reverse()[1]);
const CACHE = CW_NAME + '-v1';
const PRECACHE_URLS = %s;
self.addEventListener('install', e => e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE_URLS)).then(() => self.skipWaiting())));
self.addEventListener('activate', e => e.waitUntil(self.clients.claim()));
self.addEventListener('fetch', e => { if (e.request.method !== 'GET') return; e.respondWith(caches.match(e.request).then(r => r || fetch(e.request))); });
""" % json.dumps(["./" + x for x in files])
    with open(os.path.join(folder, "sw.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(sw)

    parent = os.path.dirname(folder)
    out = os.path.join(parent, f"{name}.cwp")
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for rel in files + ["sw.js"]:
            z.write(os.path.join(folder, rel), f"{name}/{rel}")
    dirs = {"in": "read", "out": "write", "inout": "read/write"}
    with open(os.path.join(parent, f"{name}_bindings.csv"), "w", encoding="utf-8-sig", newline="") as f:
        f.write("property;type;direction;register;tag;description\n")
        for p in props:
            f.write(";".join([p["name"], p["type"], dirs[p["dir"]], str(p.get("register", "")), str(p.get("tag", "")), p["desc"]]) + "\n")
    print(f"{len(props)} properties -> {out} ({os.path.getsize(out)} bytes)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
